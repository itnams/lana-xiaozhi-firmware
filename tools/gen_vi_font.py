#!/usr/bin/env python3
"""Generate lana_font_vi.h: a 13 px 1-bit Vietnamese bitmap font for the 128x64 SSD1306.
Base glyphs are rasterised 1-bit (no anti-aliasing) from a TTF; Vietnamese tone/vowel marks are hand-drawn pixel
bitmaps composed via Unicode NFD so they stay legible at this size (outline fonts drop them at 9-10 px).
Cell: rows 0-3 marks above capitals, cap top row 4, baseline row 10, descenders rows 11-12.
usage: gen_vi_font.py FONT.ttf SIZE OUT.h [preview.png]"""
import sys, unicodedata
from PIL import Image, ImageDraw, ImageFont

FONT, SIZE, OUT = sys.argv[1], int(sys.argv[2]), sys.argv[3]
CELL_H, BASE = 13, 10
f = ImageFont.truetype(FONT, SIZE)

M = {  # combining marks (pixel art, 'X' = lit)
    0x0302: [".X.", "X.X"],            # circumflex
    0x0306: ["X.X", ".X."],            # breve
    0x0301: [".X", "X."],              # acute
    0x0300: ["X.", ".X"],              # grave
    0x0309: ["XX", ".X", "X."],        # hook above
    0x0303: [".X.X", "X.X."],          # tilde
}
TONES = {0x0301, 0x0300, 0x0309, 0x0303}
VI = ("aàáảãạăằắẳẵặâầấẩẫậeèéẻẽẹêềếểễệiìíỉĩịoòóỏõọôồốổỗộơờớởỡợuùúủũụưừứửữựyỳýỷỹỵđ")
chars = [chr(c) for c in range(32, 127)] + list(VI) + list(VI.upper()) + ["…", "·", "°", "–"]

def raster(ch):
    im = Image.new("1", (SIZE * 2, CELL_H + 6), 0)
    d = ImageDraw.Draw(im); d.fontmode = "1"
    d.text((2, BASE + 3), ch, font=f, fill=1, anchor="ls")
    px = im.load()
    pts = {(x - 2, y - 3) for x in range(im.width) for y in range(im.height) if px[x, y]}
    adv = round(f.getlength(ch))
    return pts, adv

def put(pts, art, x0, y0):
    for dy, row in enumerate(art):
        for dx, c in enumerate(row):
            if c == "X": pts.add((x0 + dx, y0 + dy))

def glyph(ch):
    if ch in "đĐ" or ch.isascii() or ch in "…·°–":
        pts, adv = raster(ch)
        return pts, adv
    nfd = unicodedata.normalize("NFD", ch)
    base, marks = nfd[0], [ord(c) for c in nfd[1:]]
    upper = base.isupper()
    if base == "i": base = "ı"
    pts, adv = raster(base)
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    left, right, top = min(xs), max(xs), min(ys)
    cx = (left + right) / 2
    horn = 0x031B in marks
    if horn:   # small hook at the top-right
        pts |= {(right + 1, top - 1), (right + 1, top), (right, top - 1)} if base.lower() == "o" else {(right + 1, top - 1), (right + 1, top)}
        adv += 1
    if 0x0323 in marks:   # dot below
        pts.add((int(round(cx)), BASE + 2))
    mod = [m for m in marks if m in (0x0302, 0x0306)]
    tone = [m for m in marks if m in TONES]
    y = top - 1    # bottom row of the next mark sits above this row
    gap = 1 if not upper else 1
    if mod:
        art = M[mod[0]]
        y = y - gap - len(art) + 1
        put(pts, art, int(round(cx - (len(art[0]) - 1) / 2)), y)
        if tone:   # Vietnamese style: tone to the upper right of the circumflex/breve
            art2 = M[tone[0]]
            put(pts, art2, int(round(cx + (len(art[0]) - 1) / 2)) + 1, max(0, y - len(art2) + 1))
    elif tone:
        art = M[tone[0]]
        y = y - gap - len(art) + 1
        put(pts, art, int(round(cx - (len(art[0]) - 1) / 2)) + (1 if tone[0] == 0x0301 else 0), max(0, y))
    return pts, adv

glyphs = []
for ch in chars:
    pts, adv = glyph(ch)
    pts = {(x, y) for x, y in pts if 0 <= y < CELL_H}
    if pts:
        x0 = min(min(p[0] for p in pts), 0)
        w = max(p[0] for p in pts) - x0 + 1
    else:
        x0, w = 0, 0
    adv = max(adv, w + 1) if ch != " " else max(adv, 3)
    rows = []
    for y in range(CELL_H):
        bits = 0
        for x in range(w):
            if (x + x0, y) in pts: bits |= 1 << (15 - x)
        rows.append(bits)
    glyphs.append((ord(ch), w, adv, x0, rows))
glyphs.sort()
with open(OUT, "w") as o:
    o.write("// Generated by tools/gen_vi_font.py from %s @%d px - do not edit\n#pragma once\n#include <cstdint>\n" % (FONT.split('/')[-1], SIZE))
    o.write("namespace lana_font {\nstatic constexpr int kCellH = %d, kBaseline = %d;\n" % (CELL_H, BASE))
    o.write("struct Glyph { uint16_t cp; uint8_t w, adv; int8_t x0; uint16_t rows[%d]; };\n" % CELL_H)
    o.write("static const Glyph kGlyphs[] = {\n")
    for cp, w, adv, x0, rows in glyphs:
        o.write("  {0x%04X,%d,%d,%d,{%s}},\n" % (cp, w, adv, x0, ",".join("0x%X" % r for r in rows)))
    o.write("};\nstatic constexpr int kGlyphCount = %d;\n}  // namespace lana_font\n" % len(glyphs))
if len(sys.argv) > 4:
    sample = ["Đang lắng nghe… Đang nói…", "Thứ Bảy, 25/10 · Chủ Nhật", "Lana-made-by-Nael 192.168.4.1",
              "Ẩm ướt, nhiệt độ 31°C, gió", "Chào ba! Hôm nay ba thế nào?", "ỨỪỬỮỰ ếềểễệ ộổỗ ẵặ ỳỷỹ ĐƯỜNG"]
    im = Image.new("1", (128, CELL_H * len(sample)), 0); px = im.load(); g = {c[0]: c for c in glyphs}
    for li, s in enumerate(sample):
        x = 0
        for ch in s:
            cp, w, adv, x0, rows = g.get(ord(ch), g[ord("?")])
            for y in range(CELL_H):
                for k in range(w):
                    if rows[y] >> (15 - k) & 1 and 0 <= x + x0 + k < 128: px[x + x0 + k, li * CELL_H + y] = 1
            x += adv
    im.resize((512, im.height * 4), Image.NEAREST).save(sys.argv[4])
print(len(glyphs), "glyphs")
